/*==============================================================================
  STEP 00-02 : FILE FORMATS + INTERNAL STAGES
  ----------------------------------------------------------------------------
  A STAGE is a storage location for files. We use Snowflake INTERNAL stages,
  so no AWS / Azure account is needed.

      RAW.SRC_STAGE          client source extracts   (upload into /BATCH_xxx/)
      AUDIT.KEYWORD_STAGE    keyword (load) files the pipeline generates
      AUDIT.REPORT_STAGE     profiling report sent to the client

  (Future enhancement: replace RAW.SRC_STAGE with an EXTERNAL stage on an
   Amazon S3 bucket + storage integration. The COPY INTO logic stays the same.)
==============================================================================*/

USE ROLE MIG_DEVELOPER;
USE WAREHOUSE MIG_WH;
USE DATABASE HC_MIGRATION_DB;

-- Legacy extracts: pipe delimited, one header row, blanks become NULL
CREATE OR REPLACE FILE FORMAT RAW.FF_PIPE_SOURCE
    TYPE                         = CSV
    FIELD_DELIMITER              = '|'
    SKIP_HEADER                  = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL          = TRUE
    NULL_IF                      = ('')
    TRIM_SPACE                   = FALSE      -- keep spaces so profiling can detect them
    ENCODING                     = 'UTF8'
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
    COMMENT = 'Legacy payer extract layout (pipe delimited with header)';

-- Keyword files: one record per line, no field splitting (the loader splits on |)
CREATE OR REPLACE FILE FORMAT AUDIT.FF_KEYWORD
    TYPE                         = CSV
    FIELD_DELIMITER              = NONE
    RECORD_DELIMITER             = '\n'
    SKIP_HEADER                  = 0
    FIELD_OPTIONALLY_ENCLOSED_BY = NONE
    ESCAPE_UNENCLOSED_FIELD      = NONE
    NULL_IF                      = ()
    COMPRESSION                  = NONE
    COMMENT = 'Keyword load file: HDR / DTL / TRL records, pipe separated inside the line';

-- Reports for the client (profiling report, scorecard extract)
CREATE OR REPLACE FILE FORMAT AUDIT.FF_REPORT_CSV
    TYPE                         = CSV
    FIELD_DELIMITER              = ','
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF                      = ('')
    COMPRESSION                  = NONE
    COMMENT = 'Comma separated report extracts';

CREATE STAGE IF NOT EXISTS RAW.SRC_STAGE
    FILE_FORMAT = RAW.FF_PIPE_SOURCE
    DIRECTORY   = (ENABLE = TRUE)
    ENCRYPTION  = (TYPE = 'SNOWFLAKE_SSE')
    COMMENT     = 'Source extracts from the client. Upload into a folder per batch, e.g. BATCH_001/';

CREATE STAGE IF NOT EXISTS AUDIT.KEYWORD_STAGE
    FILE_FORMAT = AUDIT.FF_KEYWORD
    DIRECTORY   = (ENABLE = TRUE)
    ENCRYPTION  = (TYPE = 'SNOWFLAKE_SSE')
    COMMENT     = 'Keyword (load) files generated by dbt, consumed by SP_LOAD_FACETS_TARGET';

CREATE STAGE IF NOT EXISTS AUDIT.REPORT_STAGE
    FILE_FORMAT = AUDIT.FF_REPORT_CSV
    DIRECTORY   = (ENABLE = TRUE)
    ENCRYPTION  = (TYPE = 'SNOWFLAKE_SSE')
    COMMENT     = 'Profiling / scorecard reports to share with the client';

SHOW STAGES IN DATABASE HC_MIGRATION_DB;
