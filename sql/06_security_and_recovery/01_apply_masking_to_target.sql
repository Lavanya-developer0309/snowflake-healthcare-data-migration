/*==============================================================================
  STEP 06-01 : APPLY MASKING TO FACETS_TGT + DEMO IT
  ----------------------------------------------------------------------------
  Run once, AFTER the first successful SP_LOAD_FACETS_TARGET (the target
  tables are created by that procedure). FORCE replaces an existing policy,
  so the script is safe to re-run.
==============================================================================*/

USE ROLE MIG_DEVELOPER;
USE WAREHOUSE MIG_WH;
USE DATABASE HC_MIGRATION_DB;

ALTER TABLE FACETS_TGT.CMC_MEME_MEMBER MODIFY COLUMN MEME_SSN        SET MASKING POLICY GOVERNANCE.MP_MASK_SSN  FORCE;
ALTER TABLE FACETS_TGT.CMC_MEME_MEMBER MODIFY COLUMN MEME_BIRTH_DT   SET MASKING POLICY GOVERNANCE.MP_MASK_DOB  FORCE;
ALTER TABLE FACETS_TGT.CMC_MEME_MEMBER MODIFY COLUMN MEME_FIRST_NAME SET MASKING POLICY GOVERNANCE.MP_MASK_NAME FORCE;
ALTER TABLE FACETS_TGT.CMC_MEME_MEMBER MODIFY COLUMN MEME_LAST_NAME  SET MASKING POLICY GOVERNANCE.MP_MASK_NAME FORCE;
ALTER TABLE FACETS_TGT.CMC_SBSB_SUBSC  MODIFY COLUMN SBSB_FIRST_NAME SET MASKING POLICY GOVERNANCE.MP_MASK_NAME FORCE;
ALTER TABLE FACETS_TGT.CMC_SBSB_SUBSC  MODIFY COLUMN SBSB_LAST_NAME  SET MASKING POLICY GOVERNANCE.MP_MASK_NAME FORCE;

-- Which columns are protected?
SELECT *
FROM TABLE(HC_MIGRATION_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(
           REF_ENTITY_NAME => 'HC_MIGRATION_DB.FACETS_TGT.CMC_MEME_MEMBER',
           REF_ENTITY_DOMAIN => 'table'));

-------------------------------------------------------------------------------
-- DEMO: same query, three roles  (take a screenshot of each for the README)
-------------------------------------------------------------------------------
USE ROLE MIG_DEVELOPER;          -- clear values
SELECT MEME_CK, MEME_FIRST_NAME, MEME_LAST_NAME, MEME_BIRTH_DT, MEME_SSN
FROM HC_MIGRATION_DB.FACETS_TGT.CMC_MEME_MEMBER LIMIT 5;

USE ROLE MIG_QA;                 -- masked values
USE WAREHOUSE MIG_WH;
SELECT MEME_CK, MEME_FIRST_NAME, MEME_LAST_NAME, MEME_BIRTH_DT, MEME_SSN
FROM HC_MIGRATION_DB.FACETS_TGT.CMC_MEME_MEMBER LIMIT 5;

USE ROLE MIG_ANALYST;            -- masked values, and no access to RAW
USE WAREHOUSE MIG_WH;
SELECT MEME_CK, MEME_FIRST_NAME, MEME_LAST_NAME, MEME_BIRTH_DT, MEME_SSN
FROM HC_MIGRATION_DB.FACETS_TGT.CMC_MEME_MEMBER LIMIT 5;

