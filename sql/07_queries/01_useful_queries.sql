/*==============================================================================
  USEFUL QUERIES  - for checking a batch and for demos in interviews
==============================================================================*/

USE ROLE MIG_DEVELOPER;
USE WAREHOUSE MIG_WH;
USE DATABASE HC_MIGRATION_DB;
SET BATCH = 'BATCH_001';

-- 1. What happened in this batch, step by step?
SELECT LOGGED_AT, STEP_NAME, OBJECT_NAME, ROW_COUNT, STATUS, MESSAGE
FROM AUDIT.MIG_LOAD_LOG WHERE BATCH_ID = $BATCH ORDER BY LOG_ID;

-- 2. Batch status
SELECT * FROM AUDIT.MIG_BATCH_CONTROL ORDER BY CREATED_AT DESC;

-- 3. Files in the stages
LIST @RAW.SRC_STAGE;
LIST @AUDIT.KEYWORD_STAGE;
LIST @AUDIT.REPORT_STAGE;

-- 4. Profiling observations (what we send to the client)
SELECT TABLE_NAME, COLUMN_NAME, TOTAL_ROWS, NULL_COUNT, MIN_VALUE, MAX_VALUE, DQ_OBSERVATIONS
FROM AUDIT.V_DQ_PROFILE_REPORT
WHERE BATCH_ID = $BATCH AND DQ_OBSERVATIONS <> ''
ORDER BY TABLE_NAME, COLUMN_POSITION;

-- 5. Rejects by entity and reason
SELECT ENTITY_NAME, REJECT_REASON, COUNT(*) AS RECORDS
FROM FACETS_STG.MIG_TRANSFORM_REJECTS
WHERE MIG_BATCH_ID = $BATCH
GROUP BY ALL ORDER BY ENTITY_NAME, RECORDS DESC;

-- 6. dbt test results of the latest run
SELECT TESTED_OBJECT, TEST_NAME, SEVERITY, STATUS, FAILURES
FROM AUDIT.DBT_TEST_RESULTS
WHERE BATCH_ID = $BATCH
  AND INVOCATION_ID = (SELECT MAX_BY(INVOCATION_ID, RUN_AT) FROM AUDIT.DBT_TEST_RESULTS WHERE BATCH_ID = $BATCH)
ORDER BY STATUS DESC, TESTED_OBJECT;

-- 7. Keyword file load log
SELECT * FROM AUDIT.KEYWORD_LOAD_LOG WHERE BATCH_ID = $BATCH ORDER BY LOADED_AT DESC;

-- 8. Peek at a keyword file directly from the stage (no load needed)
SELECT $1 AS KEYWORD_RECORD
FROM @AUDIT.KEYWORD_STAGE/BATCH_001/KW_MEMBER.txt (FILE_FORMAT => 'AUDIT.FF_KEYWORD')
LIMIT 10;

-- 9. THE SCORECARD
SELECT * FROM AUDIT.V_SCORECARD WHERE BATCH_ID = $BATCH ORDER BY ENTITY_NAME;

-- 10. Error log summary
SELECT * FROM AUDIT.V_ERROR_SUMMARY WHERE BATCH_ID = $BATCH ORDER BY SEVERITY, ERROR_CATEGORY, ENTITY_NAME;

-- 11. Trace one member from source to target (lineage)
SELECT 'RAW' AS LAYER, MEMBER_ID AS KEY_VALUE, FIRST_NAME, LAST_NAME, DATE_OF_BIRTH AS DOB, GENDER_CODE AS SEX
  FROM RAW.SRC_MEMBER WHERE MEMBER_ID = 'M0000001' AND BATCH_ID = $BATCH
UNION ALL
SELECT 'FACETS_TGT', MEME_LEGACY_ID || ' -> MEME_CK ' || MEME_CK, MEME_FIRST_NAME, MEME_LAST_NAME,
       TO_VARCHAR(MEME_BIRTH_DT), MEME_SEX
  FROM FACETS_TGT.CMC_MEME_MEMBER WHERE MEME_LEGACY_ID = 'M0000001';

