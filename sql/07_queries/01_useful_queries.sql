-- 13. Query performance: the slowest queries of the pipeline today
SELECT QUERY_TEXT, TOTAL_ELAPSED_TIME / 1000 AS SECONDS, ROWS_PRODUCED, BYTES_SCANNED
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY_BY_WAREHOUSE(WAREHOUSE_NAME => 'MIG_WH', RESULT_LIMIT => 200))
ORDER BY TOTAL_ELAPSED_TIME DESC
LIMIT 10;
